// src/core/rate-limit.ts

/**
 * Максимальная длительность блокировки ключа, независимо от того, что пришло
 * в заголовке x-ratelimit-reset. Защита от багов парсинга (например, повторного
 * домножения уже нормализованного значения на 1000), которые иначе могут
 * заблокировать ключ на десятки тысяч лет вперёд.
 */
export const MAX_BLOCK_MS = 30 * 24 * 60 * 60 * 1000; // 30 дней

/**
 * Нормализует значение заголовка x-ratelimit-reset к таймстампу в миллисекундах.
 *
 * - Если значение отсутствует или не является числом — возвращает null
 *   (вызывающий код должен сам решить дефолтное поведение, например блокировать
 *   на 24 часа).
 * - Если значение похоже на unix-время в секундах (< 10^10) — домножает на 1000.
 * - Если значение уже похоже на миллисекунды (>= 10^10) — оставляет как есть.
 * - Результат в любом случае не может превышать `Date.now() + MAX_BLOCK_MS` —
 *   это единственная надёжная защита от одиночных и повторных ошибок парсинга,
 *   независимо от их причины.
 */
export function normalizeResetTimestamp(raw: string | null | undefined, now: number = Date.now()): number | null {
  if (raw === null || raw === undefined || raw === '') return null;

  let ts = parseInt(raw, 10);
  if (isNaN(ts)) return null;

  // Если ts < 10^10 (секунды) — домножаем на 1000, чтобы получить миллисекунды.
  if (ts < 10_000_000_000) {
    ts = ts * 1000;
  }

  const cap = now + MAX_BLOCK_MS;
  if (ts > cap) {
    ts = cap;
  }

  return ts;
}

/**
 * Приводит уже сохранённый (потенциально испорченным прошлым багом) blockedUntil
 * к разумной верхней границе. Используется при загрузке key-status.json, чтобы
 * старые повреждённые записи (например, блокировка на ~56000 лет) не оставались
 * в файле навсегда.
 */
export function sanitizeStoredBlockUntil(blockedUntil: number, now: number = Date.now()): number {
  const cap = now + MAX_BLOCK_MS;
  return blockedUntil > cap ? cap : blockedUntil;
}
